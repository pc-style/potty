/**
 * Writes src/safe.gen.ts: every dictionary word that the typo matcher would
 * otherwise mistake for a listed form ("shirt", "duck", "dzieci").
 *
 *   bun run gen:safe                  download the English and Polish frequency lists and use them
 *   bun run gen:safe <wordlist>...    use these files instead
 *
 * A word list has one word per line, optionally followed by a count. With no
 * arguments, /usr/share/dict/words is added when the machine has it.
 */
import { existsSync } from "node:fs"
import { flatten, nearestForm, scan } from "../src/match"

const FREQUENCY = (lang: string) => `https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/${lang}/${lang}_50k.txt`
const SYSTEM_WORDS = "/usr/share/dict/words"
const SUFFIXES = ["", "s", "es", "ed", "d", "ing", "er", "ly", "y"]

async function sources(): Promise<Array<{ text: string; inflect: boolean }>> {
	const paths = process.argv.slice(2)
	if (paths.length) return Promise.all(paths.map(async (path) => ({ text: await Bun.file(path).text(), inflect: path.endsWith("/words") })))
	const lists = await Promise.all(
		["en", "pl"].map(async (lang) => {
			const response = await fetch(FREQUENCY(lang))
			if (!response.ok) throw new Error(`${FREQUENCY(lang)}: HTTP ${response.status}`)
			return { text: await response.text(), inflect: false }
		}),
	)
	return existsSync(SYSTEM_WORDS) ? [...lists, { text: await Bun.file(SYSTEM_WORDS).text(), inflect: true }] : lists
}

const safe = new Set<string>()
for (const { text, inflect } of await sources()) {
	for (const line of text.split("\n")) {
		const word = flatten((line.split(" ")[0] ?? "").toLowerCase())
		if (!/^[a-z]{4,16}$/.test(word)) continue
		// A plain dictionary lists base forms only, so add the common English endings.
		for (const suffix of inflect ? SUFFIXES : [""]) {
			const candidate = word + suffix
			if (safe.has(candidate)) continue
			// Only words that reach the typo step need listing; listed forms and stems match earlier.
			if (nearestForm(candidate) && scan(candidate).every((hit) => hit.kind === "variant")) safe.add(candidate)
		}
	}
}

const words = [...safe].sort()
await Bun.write(
	new URL("../src/safe.gen.ts", import.meta.url),
	`// Generated by scripts/gen-safe.ts. Do not edit.\nexport const SAFE_WORDS: ReadonlySet<string> = new Set(\n\t"${words.join(" ")}".split(" "),\n)\n`,
)
console.log(`${words.length} safe words`)
